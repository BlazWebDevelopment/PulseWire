export function getArticleBySlug(slug: string): Article | undefined {
  return articles.find((a) => a.slug === slug);
}

export function getArticlesByCategory(category: string): Article[] {
  return articles.filter((a) => a.category === category);
}

export function getFeaturedArticles(): Article[] {
  return articles.filter((a) => a.featured);
}

export function getTrendingArticles(): Article[] {
  return articles.filter((a) => a.trending);
}

export function getLatestArticles(count: number): Article[] {
  return [...articles]
    .sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime())
    .slice(0, count);
}

export function searchArticles(query: string): Article[] {
  const q = query.toLowerCase();
  return articles.filter(
    (a) =>
      a.title.toLowerCase().includes(q) ||
      a.excerpt.toLowerCase().includes(q) ||
      a.tags.some((t) => t.toLowerCase().includes(q)) ||
      a.category.toLowerCase().includes(q) ||
      a.author.toLowerCase().includes(q),
  );
}

export function getRelatedArticles(article: Article, count: number): Article[] {
  const scored = articles
    .filter((a) => a.id !== article.id)
    .map((a) => {
      let score = 0;
      if (a.category === article.category) score += 3;
      const sharedTags = a.tags.filter((t) => article.tags.includes(t)).length;
      score += sharedTags * 2;
      return { article: a, score };
    })
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, count).map((s) => s.article);
}
